#!/usr/bin/env python3
"""Regenerate sw.js from sw.js.template.

Run after every change to the app files:  python3 scripts/build_sw.py
- PRECACHE lists every file the app needs offline (the large numbered Korean
  font subsets are left out; the service worker caches them once they are used).
- VERSION is a hash of those files, so any change produces a new service worker
  and the app offers the update.
"""
import hashlib, json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FILES = ['index.html', 'manifest.webmanifest', 'css/app.css', 'js/qr.js', 'js/app.js', 'fonts/fonts.css']
FILES += sorted('icons/' + f for f in os.listdir(os.path.join(ROOT, 'icons')) if f.endswith(('.png', '.svg')))
FILES += sorted('fonts/' + f for f in os.listdir(os.path.join(ROOT, 'fonts'))
                if f.endswith('.woff2') and re.search(r'-latin(-ext)?-\d+-normal\.woff2$', f))

# a thread that was removed for good must never come back (see CLAUDE.md); the word is split so this file doesn't match
BANNED = 'bet' + 'ting'
for d, dirs, files in os.walk(ROOT):
    dirs[:] = [x for x in dirs if x != '.git']
    for f in files:
        try:
            with open(os.path.join(d, f), encoding='utf-8') as fh:
                if BANNED in fh.read().lower():
                    raise SystemExit('Removed thread found in ' + os.path.relpath(os.path.join(d, f), ROOT) + ' - it must not come back (see CLAUDE.md).')
        except UnicodeDecodeError:
            pass

h = hashlib.sha256()
for f in FILES:
    with open(os.path.join(ROOT, f), 'rb') as fh:
        h.update(f.encode() + b'\0' + fh.read())
version = h.hexdigest()[:12]

with open(os.path.join(ROOT, 'sw.js.template'), encoding='utf-8') as fh:
    tpl = fh.read()
precache = ['./'] + ['./' + f for f in FILES]
out = tpl.replace('__VERSION__', version).replace('__PRECACHE__', json.dumps(precache, indent=2))
out = out.replace('GENERATED from sw.js.template by scripts/build_sw.py; do not edit sw.js by hand.',
                  'Generated by scripts/build_sw.py from sw.js.template — edit the template, not this file.')
with open(os.path.join(ROOT, 'sw.js'), 'w', encoding='utf-8') as fh:
    fh.write(out)
print('sw.js version', version, '-', len(precache), 'files')
