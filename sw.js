self.addEventListener('install', event => {
  event.waitUntil(
    caches.open(SHELL).then(cache => cache.addAll(PRECACHE.map(u => new Request(u, {cache: 'reload'}))))
  );
});

self.addEventListener('activate', event => {
  event.waitUntil((async () => {
    const keys = await caches.keys();
    await Promise.all(keys.filter(k => k.startsWith('memochat-') && k !== SHELL && k !== FONTS).map(k => caches.delete(k)));
    await self.clients.claim();
  })());
});

self.addEventListener('message', event => {
  if (event.data === 'skipWaiting') self.skipWaiting();
});

/* ---------- Share target: other apps → MemoChat ----------
   Android sends the shared text/link/photo as a POST to ./share-target.
   We park it in IndexedDB (key 'share', same database as the app) and open the app,
   which then asks which thread it goes to. Nothing leaves the device. */
const SHARE_PATH = new URL('./share-target', self.registration.scope).pathname;
function idbPut(key, value) {
  return new Promise((resolve, reject) => {
    const r = indexedDB.open('memochat', 1);
    r.onupgradeneeded = () => r.result.createObjectStore('kv');
    r.onerror = () => reject(r.error);
    r.onsuccess = () => {
      const db = r.result, tx = db.transaction('kv', 'readwrite');
      tx.objectStore('kv').put(value, key);
      tx.oncomplete = () => { db.close(); resolve(); };
      tx.onerror = () => { db.close(); reject(tx.error); };
    };
  });
}
async function handleShare(req) {
  try {
    const fd = await req.formData();
    const s = v => (typeof v === 'string' ? v.slice(0, 100000) : '');
    const files = fd.getAll('files').filter(f => f && typeof f === 'object' && f.size > 0 && /^image\//.test(f.type));
    await idbPut('share', {title: s(fd.get('title')), text: s(fd.get('text')), url: s(fd.get('url')),
                           files: files.slice(0, 1), extraFiles: Math.max(0, files.length - 1), at: Date.now()});
  } catch (e) { /* open the app anyway */ }
  return Response.redirect(new URL('./?share=1', self.registration.scope).href, 303);
}

self.addEventListener('fetch', event => {
  const req = event.request;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;   // never touch other sites
  if (req.method === 'POST' && url.pathname === SHARE_PATH) { event.respondWith(handleShare(req)); return; }
  if (req.method !== 'GET') return;

  // App pages: always the cached shell (works offline); network only as a fallback.
  if (req.mode === 'navigate') {
    event.respondWith((async () => {
      const cache = await caches.open(SHELL);
      const hit = await cache.match('./index.html');
      if (hit) return hit;
      try { return await fetch(req); }
      catch (e) { return new Response('MemoChat is offline and not installed yet.', {status: 503, headers: {'Content-Type': 'text/plain; charset=utf-8'}}); }
    })());
    return;
  }

  event.respondWith((async () => {
    // look only in this version's shell cache (never mix files from a newer, still-waiting version)
    const hit = (await (await caches.open(SHELL)).match(req, {ignoreSearch: true}))
             || (await (await caches.open(FONTS)).match(req));
    if (hit) return hit;
    const res = await fetch(req);
    // keep font subsets once they have been used, so they work offline afterwards
    if (res.ok && url.pathname.includes('/fonts/') && url.pathname.endsWith('.woff2')) {
      const copy = res.clone();
      event.waitUntil(caches.open(FONTS).then(c => c.put(req, copy)));
    }
    return res;
  })());
});
